#!/usr/bin/env python3
"""Import pinned G1 source meshes and USD payloads into bindu_description.

The control model stays unchanged. Only generated physics/import caches belong
in artifacts; source meshes, source USD and textures belong to the asset package.
"""
import argparse
import copy
import hashlib
import json
from pathlib import Path
import tarfile
import urllib.request
import xml.etree.ElementTree as ET
from derive_g1_model import REVISION, SOURCE_SHA256

ROOT = Path(__file__).resolve().parents[1]
DESCRIPTION = ROOT/'src/hardware/bindu_description'
ARCHIVE_SHA256 = 'efa6ff84b0393f680915a42f667f02afe8c0303d4edea9d4955dd6bdcf4b5fef'
MANIFEST = 'g1.assets.json'
PREFIX = 'package://bindu_description/'


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def source_repository(cache):
    cache.mkdir(parents=True,exist_ok=True)
    archive=cache/'source.tar.gz'
    if not archive.is_file():
        urllib.request.urlretrieve(f'https://codeload.github.com/GalaxyGeneralRobotics/galbot_one_golf_description/tar.gz/{REVISION}',archive)
    if digest(archive)!=ARCHIVE_SHA256:
        raise ValueError('G1_ARCHIVE_CHECKSUM_MISMATCH')
    with tarfile.open(archive) as bundle:
        bundle.extractall(cache,filter='data')
    return cache/f'galbot_one_golf_description-{REVISION}'


def prepare(source,output=DESCRIPTION):
    source=Path(source).resolve();output=Path(output)
    if digest(source/'urdf/galbot_one_golf.urdf')!=SOURCE_SHA256:
        raise ValueError('G1_SOURCE_VERSION_MISMATCH')
    if (source/'LICENSE').read_bytes()!=(DESCRIPTION/'LICENSE').read_bytes():
        raise ValueError('G1_SOURCE_LICENSE_MISMATCH')
    control=output/'urdf/g1_provisional.urdf'
    if not control.is_file():
        # A temporary output can reuse the checked-in control model.
        control=DESCRIPTION/'urdf/g1_provisional.urdf'
    robot=ET.parse(control).getroot()
    upstream={link.get('name'):link for link in ET.parse(source/'urdf/galbot_one_golf.urdf').getroot().findall('link')}
    blobs={};source_meshes={};mesh_content={}
    for link in robot.findall('link'):
        for original in upstream[link.get('name')]:
            if original.tag not in ('visual','collision'):continue
            geometry=copy.deepcopy(original)
            for mesh in geometry.iter('mesh'):
                name=Path(mesh.get('filename'))
                if name.is_absolute() or '..' in name.parts or name.parts[0]!='meshes':
                    raise ValueError('G1_INVALID_MESH_PATH')
                path=(source/'urdf'/name).resolve()
                if not path.is_relative_to(source):raise ValueError('G1_INVALID_MESH_PATH')
                data=path.read_bytes();sha=hashlib.sha256(data).hexdigest()
                dest=mesh_content.setdefault(sha,'meshes/g1/'+str(name.relative_to('meshes')))
                blobs[dest]=data;source_meshes[str(name)]=dest
                mesh.set('filename',PREFIX+dest)
            link.append(geometry)
    # Isaac restores visuals from payloads/base.usda. Its dependency closure is
    # the six top-level payload files and Textures; upstream ROS/physics/sensor
    # variants and the demo environment are not used by Bindu.
    usd_paths=list((source/'usd/payloads').glob('*'))+list((source/'usd/Textures').rglob('*'))
    for path in sorted(usd_paths):
        if path.is_file():
            if not path.resolve().is_relative_to(source):raise ValueError('G1_INVALID_USD_PATH')
            blobs['usd/g1/'+str(path.relative_to(source/'usd'))]=path.read_bytes()
    blobs['urdf/g1_provisional.urdf']=control.read_bytes()
    ET.indent(robot,space='  ')
    header=('<?xml version="1.0"?>\n<!-- Generated by tools/prepare_g1_description.py; do not hand-edit.\n'
            f'     Upstream commit {REVISION}; Apache-2.0, see ../LICENSE.\n'
            '     Same kinematics as g1_provisional.urdf; source visual/collision geometry restored.\n'
            '     Provisional model, not calibrated hardware. -->\n')
    blobs['urdf/g1_display.urdf']=(header+ET.tostring(robot,encoding='unicode')+'\n').encode()
    pinned_path=DESCRIPTION/MANIFEST
    pinned=json.loads(pinned_path.read_text()) if pinned_path.is_file() else None
    # Mesh/USD inputs cannot silently drift while the source URDF stays the same.
    if pinned:
        for name,data in blobs.items():
            if name.startswith(('meshes/','usd/')) and (
                    name not in pinned['files'] or hashlib.sha256(data).hexdigest()!=pinned['files'][name]['sha256']):
                raise ValueError('G1_SOURCE_RESOURCE_MISMATCH: '+name)
    manifest={'schema_version':1,'asset_id':'g1_provisional','source':{'repository':'GalaxyGeneralRobotics/galbot_one_golf_description',
        'revision':REVISION,'urdf_sha256':SOURCE_SHA256,'archive_sha256':ARCHIVE_SHA256,'license':'Apache-2.0'},
        'models':{'control':'urdf/g1_provisional.urdf','display':'urdf/g1_display.urdf'},
        'source_meshes':source_meshes,'source_usd':'usd/g1',
        'files':{name:{'sha256':hashlib.sha256(data).hexdigest(),'bytes':len(data)} for name,data in sorted(blobs.items())},
        'counts':{'meshes':len(mesh_content),'mesh_references':len(source_meshes),
                  'source_usd_files':sum(name.startswith('usd/') for name in blobs)},
        'current_robot_calibration':False}
    for name,data in blobs.items():
        path=output/name;path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(data)
    (output/MANIFEST).write_text(json.dumps(manifest,indent=2)+'\n')
    return manifest


def verify_description(description):
    description=Path(description).resolve();path=description/MANIFEST
    if not path.is_file():raise ValueError('G1_ASSETS_NOT_PREPARED: run tools/prepare_g1_description.py')
    manifest=json.loads(path.read_text())
    if manifest['source']['revision']!=REVISION or manifest['source']['urdf_sha256']!=SOURCE_SHA256:
        raise ValueError('G1_ASSET_SOURCE_VERSION_MISMATCH')
    expected={name for name in manifest['files'] if name.startswith(('meshes/g1/','usd/g1/'))}
    actual={str(file.relative_to(description)) for directory in ('meshes/g1','usd/g1')
            for file in (description/directory).rglob('*') if file.is_file()}
    if actual!=expected:
        raise ValueError('G1_ASSET_LAYOUT_MISMATCH: remove stale files or use a clean package install')
    for name,entry in manifest['files'].items():
        relative=Path(name)
        if relative.is_absolute() or '..' in relative.parts:raise ValueError('G1_INVALID_ASSET_PATH')
        file=description/relative
        if not file.is_file() or digest(file)!=entry['sha256']:
            raise ValueError('G1_ASSET_CHECKSUM_MISMATCH: '+name)
    return manifest


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source',type=Path,help='Pinned upstream repository; otherwise download a checksum-verified archive')
    parser.add_argument('--output',type=Path,default=DESCRIPTION)
    parser.add_argument('--cache',type=Path,default=ROOT/'artifacts/asset-sources/g1')
    args=parser.parse_args();source=args.source or source_repository(args.cache)
    manifest=prepare(source,args.output);print(json.dumps(manifest['counts']))


if __name__=='__main__':main()
