#!/usr/bin/env python3
"""Import the fixed legacy v3.4 Huawei model into bindu_description.

The historical originals are read-only. Kinematic and display variants share
one model structure; equal mesh bytes are stored once, even under source aliases.
"""
import argparse
import copy
import hashlib
import json
from pathlib import Path
import struct
import xml.etree.ElementTree as ET

SOURCE_SHA256 = 'f563c37245d605dbb301207723ae9e6677497dc3f2541e0b1dc6ec8e6cc785a1'
SOURCE = 'v3.4/ik_solver/huawei-urdf-body_hand/huawei_urdf_wheel.urdf'
DESCRIPTION = Path(__file__).resolve().parents[1]/'src/hardware/bindu_description'
MANIFEST = 'huawei_v34.assets.json'
PREFIX = 'package://bindu_description/'


def digest(data):
    return hashlib.sha256(data).hexdigest()


def model_bytes(root, purpose):
    ET.indent(root, space='  ')
    header = ('<?xml version="1.0"?>\n<!-- Generated by tools/prepare_huawei_description.py; do not hand-edit.\n'
              f'     Source: {SOURCE}; SHA256: {SOURCE_SHA256}\n'
              f'     Purpose: {purpose}\n'
              '     Historical reference, not current-robot calibration; see ../HUAWEI_ASSETS_NOTICE. -->\n')
    return (header+ET.tostring(root, encoding='unicode')+'\n').encode()


def prepare(source, mesh_root, output):
    data = source.read_bytes()
    if digest(data) != SOURCE_SHA256:
        raise ValueError('HUAWEI_SOURCE_VERSION_MISMATCH')
    root = ET.fromstring(data)
    names = sorted({mesh.get('filename') for mesh in root.iter('mesh')})
    if len(root.findall('link')) != 90 or len(names) != 101:
        raise ValueError('HUAWEI_SOURCE_LAYOUT_MISMATCH')
    pinned_path = DESCRIPTION/MANIFEST
    pinned = json.loads(pinned_path.read_text())['source_meshes'] if pinned_path.is_file() else None
    if pinned is not None and set(pinned) != set(names):
        raise ValueError('HUAWEI_PINNED_MESH_LAYOUT')
    blobs, source_meshes, canonical = {}, {}, {}
    for name in names:
        relative = Path(name)
        if len(relative.parts) != 2 or relative.parts[0] != 'meshes' or relative.suffix.lower() != '.stl':
            raise ValueError('HUAWEI_SOURCE_MESH_PATH')
        path = (mesh_root/relative).resolve()
        if not path.is_relative_to(mesh_root.resolve()):
            raise ValueError('HUAWEI_SOURCE_MESH_PATH')
        data = path.read_bytes()
        if len(data)<84 or (n:=struct.unpack('<I',data[80:84])[0])==0 or len(data)!=84+50*n:
            raise ValueError('HUAWEI_INVALID_BINARY_STL: '+name)
        sha = digest(data)
        if pinned is not None and sha != pinned[name]['sha256']:
            raise ValueError('HUAWEI_SOURCE_MESH_HASH_MISMATCH: '+name)
        dest = canonical.setdefault(sha, 'meshes/huawei_v34/'+relative.name)
        blobs[dest] = data
        source_meshes[name] = {'sha256':sha, 'bytes':len(data), 'destination':dest}
    for mesh in root.iter('mesh'):
        mesh.set('filename', PREFIX+source_meshes[mesh.get('filename')]['destination'])
    control = copy.deepcopy(root)
    for link in control.findall('link'):
        for geometry in list(link):
            if geometry.tag in ('visual','collision'):
                link.remove(geometry)
    blobs['urdf/huawei_v34_kinematic.urdf'] = model_bytes(control, 'FK/IK kinematics; visual/collision geometry omitted.')
    blobs['urdf/huawei_v34_display.urdf'] = model_bytes(root, 'Legacy display and source collision geometry; no physical validation.')
    manifest = {'schema_version':1, 'asset_id':'huawei_v34',
        'source':{'urdf':SOURCE, 'urdf_sha256':SOURCE_SHA256,
                  'mesh_origin':'user-provided old-computer backup Music/huawei_new/meshes',
                  'license':'NOASSERTION'},
        'models':{'kinematic':'urdf/huawei_v34_kinematic.urdf', 'display':'urdf/huawei_v34_display.urdf'},
        'source_meshes':source_meshes,
        'files':{name:{'sha256':digest(data),'bytes':len(data)} for name,data in sorted(blobs.items())},
        'counts':{'links':len(root.findall('link')), 'source_mesh_names':len(names),
                  'stored_meshes':len(canonical), 'deduplicated_aliases':len(names)-len(canonical)},
        'physical_validation':False, 'current_robot_calibration':False}
    # Validate every source before writing any output. Never remove historical assets.
    for name,data in blobs.items():
        path = output/name;path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(data)
    (output/MANIFEST).write_text(json.dumps(manifest,indent=2)+'\n')
    return manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path, help='Original v3.4 huawei_urdf_wheel.urdf')
    parser.add_argument('--mesh-root', type=Path, help='Directory containing the original meshes/ subdirectory')
    parser.add_argument('--output', type=Path, default=DESCRIPTION)
    args = parser.parse_args()
    manifest = prepare(args.source, args.mesh_root or args.source.parent, args.output)
    print(json.dumps(manifest['counts']))


if __name__=='__main__':main()
