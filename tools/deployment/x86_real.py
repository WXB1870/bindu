"""Prepare/build the existing Snowbot real VR chain in one isolated x86 workspace."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import platform
import shlex
import subprocess
import sys

from tools import ROOT

REQUIREMENTS = ROOT/'tools/requirements/requirements-x86-real.txt'
TEMPLATE = ROOT/'src/integration/bindu_runtime/config/deployments/snowbot_vr_real.json'
SYSTEM_PATH = '/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin'
OVERLAYS = ('PYTHONPATH', 'PYTHONHOME', 'AMENT_PREFIX_PATH', 'COLCON_PREFIX_PATH',
            'CMAKE_PREFIX_PATH', 'LD_LIBRARY_PATH', 'LD_PRELOAD', 'LIBRARY_PATH',
            'CPATH', 'CPLUS_INCLUDE_PATH', 'PKG_CONFIG_PATH', '_PYTHON_SYSCONFIGDATA_NAME',
            'VIRTUAL_ENV', 'CONDA_PREFIX',
            'CONDA_DEFAULT_ENV', 'BINDU_TELEOP_DEPS', 'BINDU_VIEWER_DEPS',
            'BINDU_VR_ENV', 'BINDU_VR_CONFIG', 'ROS_DISTRO', 'ROS_VERSION',
            'ROS_PYTHON_VERSION', 'ROS_PACKAGE_PATH')


def target_distro(os_info, machine, version):
    if machine not in ('x86_64', 'AMD64'):
        raise ValueError('此入口仅支持 x86_64')
    target = {'22.04': ('humble', (3, 10)), '24.04': ('jazzy', (3, 12))}
    if os_info.get('ID') != 'ubuntu' or os_info.get('VERSION_ID') not in target:
        raise ValueError('需要 Ubuntu 22.04/Humble 或 Ubuntu 24.04/Jazzy')
    distro, expected = target[os_info['VERSION_ID']]
    if tuple(version[:2]) != expected:
        raise ValueError('系统 Python 与目标 ROS ABI 不匹配')
    return distro


def clean_environment():
    env = {key: value for key, value in os.environ.items()
           if key not in OVERLAYS and not key.startswith(('CONDA_', '_CE_'))}
    env.update(PATH=SYSTEM_PATH, PYTHONNOUSERSITE='1', PYTHONDONTWRITEBYTECODE='1',
               OPENBLAS_NUM_THREADS='1', OMP_NUM_THREADS='1')
    # Avoid 118's cross-user Fast DDS default-transport receive failure.
    # Apply this before sourcing even an existing deployment's older env.sh.
    env['FASTDDS_BUILTIN_TRANSPORTS'] = env.get('FASTDDS_BUILTIN_TRANSPORTS') or 'UDPv4'
    return env


def system_target():
    info = platform.freedesktop_os_release()
    version = json.loads(subprocess.check_output(
        ['/usr/bin/python3', '-c', 'import json,sys; print(json.dumps(list(sys.version_info[:2])))'],
        text=True, env=clean_environment()))
    return target_distro(info, platform.machine(), version), version


def environment_script(workspace, profile):
    q = shlex.quote
    version = '.'.join(map(str, profile['python']))
    site = workspace/f'venv/lib/python{version}/site-packages'
    cmeel = site/'cmeel.prefix'
    return '\n'.join([
        '# Generated by tools.deployment.x86_real; use only on this machine.',
        '# Reset inherited overlays; preserve the caller\'s DDS/domain settings.',
        'unset '+' '.join(OVERLAYS),
        'export PATH='+q(SYSTEM_PATH),
        'export PYTHONNOUSERSITE=1 PYTHONDONTWRITEBYTECODE=1',
        'export OPENBLAS_NUM_THREADS=1 OMP_NUM_THREADS=1',
        'export FASTDDS_BUILTIN_TRANSPORTS="${FASTDDS_BUILTIN_TRANSPORTS:-UDPv4}"',
        'export CMAKE_BUILD_PARALLEL_LEVEL="${CMAKE_BUILD_PARALLEL_LEVEL:-2}"',
        'source '+q(f"/opt/ros/{profile['ros']}/setup.bash")+' || return',
        'source '+q(profile['vendor_setup'])+' || return',
        'source '+q(str(workspace/'venv/bin/activate'))+' || return',
        'export CMAKE_PREFIX_PATH='+q(str(cmeel))+'${CMAKE_PREFIX_PATH:+:$CMAKE_PREFIX_PATH}',
        'export LD_LIBRARY_PATH='+q(str(cmeel/'lib'))+'${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}',
        # Vuer's transitive old argparse backport must not shadow the stdlib.
        'export PYTHONPATH='+q(f'/usr/lib/python{version}:{cmeel}/lib/python{version}/site-packages')+
        '${PYTHONPATH:+:$PYTHONPATH}',
        'if [[ -f '+q(str(workspace/'install/local_setup.bash'))+' ]]; then',
        '  source '+q(str(workspace/'install/local_setup.bash'))+' || return',
        'fi',
        'export BINDU_VIEWER_DEPS='+q(str(site)),
        'export BINDU_VR_ENV='+q(str(workspace/'env.sh')),
        'export BINDU_VR_CONFIG='+q(str(workspace/'site.json')),
        '',
    ])


def in_environment(workspace, command, replace=False):
    shell = ['bash', '--noprofile', '--norc', '-ec',
             'source "$1"; shift; exec "$@"', 'bindu-x86', str(workspace/'env.sh'), *map(str, command)]
    if replace:
        # Keep the launcher's existing Ctrl+C/stop handshake as the foreground process.
        os.chdir(ROOT)
        os.execvpe('bash', shell, clean_environment())
    return subprocess.run(shell, cwd=ROOT, env=clean_environment(), check=True)


def read_profile(workspace):
    profile = json.loads((workspace/'deployment.json').read_text())
    distro, version = system_target()
    if (profile.get('schema') != 1 or profile.get('root') != str(ROOT) or
            profile.get('workspace') != str(workspace) or profile.get('ros') != distro or
            profile.get('python') != version):
        raise ValueError('部署目录属于其他源码路径或系统；请在新目录重新 prepare')
    return profile


def source_digest():
    paths = subprocess.check_output(
        ['git', 'ls-files', '--cached', '--others', '--exclude-standard', '-z',
         '--', 'src', 'tools/requirements'], cwd=ROOT).split(b'\0')
    digest = hashlib.sha256()
    for raw in sorted(path for path in paths if path and not path.endswith(b'.md')):
        digest.update(raw+b'\0')
        digest.update((ROOT/os.fsdecode(raw)).read_bytes())
    return digest.hexdigest()


def require_current_build(workspace):
    build_info = json.loads((workspace/'build.json').read_text())
    if not build_info.get('ready') or build_info.get('source_sha256') != source_digest():
        raise ValueError('构建未完成或源码/依赖清单已变更，请重新 build')


def prepare(options):
    workspace = options.workspace
    distro, version = system_target()
    if options.ros_distro and options.ros_distro != distro:
        raise ValueError('Ubuntu/Python 与所选 ROS 发行版不匹配')
    if not Path(f'/opt/ros/{distro}/setup.bash').is_file():
        raise ValueError('请先安装 ROS '+distro+'，以及文档列出的系统依赖')
    vendor = options.vendor_setup.expanduser().resolve()
    if not vendor.is_file() or vendor.name != 'local_setup.bash':
        raise ValueError('--vendor-setup 需要已适配底层消息安装目录的 local_setup.bash')
    profile = dict(schema=1, root=str(ROOT), workspace=str(workspace), ros=distro,
                   python=version, vendor_setup=str(vendor), ready=False)
    if workspace.exists() and any(workspace.iterdir()):
        old = read_profile(workspace)
        if old['vendor_setup'] != str(vendor):
            raise ValueError('已有部署目录使用另一底层环境，请新建目录')
    else:
        workspace.mkdir(parents=True, exist_ok=True)
    (workspace/'deployment.json').write_text(json.dumps(profile, indent=2)+'\n')
    subprocess.run(['/usr/bin/python3', '-m', 'venv', '--system-site-packages', str(workspace/'venv')],
                   check=True, env=clean_environment())
    subprocess.run([str(workspace/'venv/bin/python3'), '-m', 'pip', 'install', '-r', str(REQUIREMENTS)],
                   check=True, env=clean_environment())
    (workspace/'env.sh').write_text(environment_script(workspace, profile))
    # Use package local_setup only: do not replay historical Bindu underlay chains.
    in_environment(workspace, ['python3', '-c',
        'import rclpy; from rclpy.type_support import check_for_type_support; '
        'from snowbot_ctl_msgs.msg import JointPositionCommand,RetInformation; '
        'check_for_type_support(JointPositionCommand); check_for_type_support(RetInformation); '
        'import numpy,scipy,pinocchio,casadi,meshcat,vuer'])
    site = workspace/'site.json'
    if not site.exists():
        with site.open('x') as stream:
            stream.write(TEMPLATE.read_text())
    profile['ready'] = True
    (workspace/'deployment.json').write_text(json.dumps(profile, indent=2)+'\n')
    print(f'已准备 {workspace}；现场配方 {site} 默认只读。下一步执行 build。')


def build(workspace):
    before = source_digest()
    info = dict(ready=False, source_sha256=before)
    (workspace/'build.json').write_text(json.dumps(info, indent=2)+'\n')
    command = ['python3', '/usr/bin/colcon', '--log-base', workspace/'log', 'build',
        '--base-paths', ROOT/'src', '--packages-up-to', 'bindu_runtime', 'bindu_bimanual_qp',
        '--build-base', workspace/'build', '--install-base', workspace/'install',
        '--executor', 'sequential', '--cmake-args', '-DCMAKE_BUILD_TYPE=Release',
        '-DPython3_EXECUTABLE='+str(workspace/'venv/bin/python3'),
        '-DPYTHON_EXECUTABLE='+str(workspace/'venv/bin/python3')]
    in_environment(workspace, command)
    # Actual loaded modules/paths plus the resolved pip set are useful on a second machine.
    in_environment(workspace, ['python3', '-c', '''
import importlib, json, os, platform, subprocess, sys
from pathlib import Path
from ament_index_python.packages import get_package_prefix
modules={}
for name in ('numpy','scipy','pinocchio','casadi','rclpy','bindu_execution._native'):
    module=importlib.import_module(name)
    modules[name]={'version':getattr(module,'__version__',None),'file':module.__file__}
data={'python':sys.executable,'architecture':platform.machine(),'ros':os.environ['ROS_DISTRO'],
      'commit':subprocess.check_output(['git','rev-parse','HEAD'],text=True).strip(),
      'dirty':bool(subprocess.check_output(['git','status','--porcelain'],text=True)),
      'prefixes':{name:get_package_prefix(name) for name in
                  ('bindu_runtime','bindu_interfaces','bindu_bimanual_qp','snowbot_ctl_msgs')},
      'modules':modules}
out=Path(sys.argv[1])
(out/'environment.json').write_text(json.dumps(data,indent=2)+'\\n')
(out/'requirements-resolved.txt').write_text(subprocess.check_output(
    [sys.executable,'-m','pip','freeze','--local'],text=True))
''', workspace])
    if source_digest() != before:
        raise ValueError('构建期间源码发生变化，请重新 build')
    info['ready'] = True
    (workspace/'build.json').write_text(json.dumps(info, indent=2)+'\n')


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=('prepare', 'build', 'check', 'check-robot', 'start'))
    parser.add_argument('--workspace', type=Path, default=ROOT/'artifacts/x86-real')
    parser.add_argument('--vendor-setup', type=Path)
    parser.add_argument('--ros-distro', choices=('humble', 'jazzy'))
    options, extra = parser.parse_known_args(argv)
    options.workspace = options.workspace.expanduser().resolve()
    try:
        if options.command == 'prepare':
            if extra or not options.vendor_setup:
                raise ValueError('prepare 需要 --vendor-setup，且不接受启动参数')
            prepare(options)
        else:
            if options.vendor_setup or options.ros_distro:
                raise ValueError('--vendor-setup/--ros-distro 仅用于 prepare')
            if not read_profile(options.workspace).get('ready'):
                raise ValueError('prepare 尚未成功完成')
            if options.command == 'build':
                if extra:
                    raise ValueError('build 不接受启动参数')
                build(options.workspace)
            else:
                if not (options.workspace/'install/local_setup.bash').is_file():
                    raise ValueError('请先执行 build')
                require_current_build(options.workspace)
                site = json.loads((options.workspace/'site.json').read_text())['arguments']
                if site.get('runtime_mode') != 'real' or site.get('device_backend') != 'snowbot_vendor':
                    raise ValueError('此部署入口需要 real/snowbot_vendor 现场配方')
                if any(value == '--config' or value.startswith('--config=') or value == '--physics'
                       for value in extra):
                    raise ValueError('请直接编辑现场 site.json；此入口不接受 --config/--physics')
                # Explicit config prevents a machine-local simulation default leaking in.
                command = ['bash', ROOT/'tools/run_vr.sh', *extra, '--config', options.workspace/'site.json']
                if options.command in ('check', 'check-robot'):
                    command.append('--check')
                if options.command == 'check-robot':
                    command.append('--check-robot')
                in_environment(options.workspace, command, replace=options.command == 'start')
        return 0
    except (OSError, ValueError, KeyError, TypeError, subprocess.CalledProcessError) as exc:
        print('x86 部署失败：'+str(exc), file=sys.stderr)
        return 2


if __name__ == '__main__':
    sys.exit(main())
