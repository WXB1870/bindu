#!/usr/bin/env python3
"""Generate three Snowbot URDF variants and one shared mesh directory.

The original archive supplies geometry and Bindu extension frames. The checked
user-supplied joint model supplies the twenty shared movable joints. snowbot.urdf repairs the
duplicated F/T joint names and rewrites mesh URIs to meshes/snowbot/ in the
snowbot_description package. snowbot_display.urdf additionally fixes the four
wheel joints. snowbot_control.urdf removes visual/collision geometry from the
display model, retaining its 20 movable axes for IK and bimanual QP.
The distal eighth arm axes remain in the model and measured context but are
left to a future tool adapter; their grasp role is not specified by the URDF.
Regenerate all variants together; do not maintain them by hand.
"""
from tools import package_share
import argparse
import hashlib
import copy
from pathlib import Path
from tools import ROOT
import xml.etree.ElementTree as ET
from zipfile import ZipFile


SOURCE_SHA256 = '6d0786fe497d9021866b74e18cc64937fa3e6e31a7f8969efd208f013c788858'
JOINT_SOURCE = package_share("snowbot_description")/'sources/snowbot.urdf'
JOINT_SOURCE_SHA256 = '3024f5e3b45b188db7f3c0d1e13eaabb86ef726bd75b3c61d9984ced84c00798'
SOURCE_PREFIX = 'snowbot_20260728_首次全身/snowbot/'
ACTIVE = {'body_joint_1', 'body_joint_2'} | {
    f'arm_{side}_joint_{axis}' for side in ('l', 'r') for axis in range(1, 8)
}


def write_model(root, path, purpose):
    ET.indent(root, space='  ')
    notice = ('<?xml version="1.0"?>\n<!-- Generated by tools/models/prepare_snowbot_description.py; do not hand-edit.\n'
              f'     Source archive SHA256: {SOURCE_SHA256}\n'
              f'     Shared joint source SHA256: {JOINT_SOURCE_SHA256}\n'
              f'     Purpose: {purpose}\n'
              '     Mesh variants share ../meshes/snowbot/; see ../SNOWBOT_ASSETS_NOTICE. -->\n')
    path.write_text(notice + ET.tostring(root, encoding='unicode') + '\n', encoding='utf-8')


def apply_joint_source(root, source=JOINT_SOURCE):
    data = source.read_bytes()
    if hashlib.sha256(data).hexdigest() != JOINT_SOURCE_SHA256:
        raise ValueError('SNOWBOT_JOINT_SOURCE_HASH_MISMATCH')
    model = ET.fromstring(data)
    expected = ACTIVE | {'head_joint_1', 'head_joint_2', 'arm_l_joint_8', 'arm_r_joint_8'}
    supplied = [j for j in model.findall('joint') if j.get('type') != 'fixed']
    if model.get('name') != 'snowbot' or len(supplied) != len(expected) or {j.get('name') for j in supplied} != expected:
        raise ValueError('SNOWBOT_JOINT_SOURCE_LAYOUT')
    current = {j.get('name'): j for j in root.findall('joint')}
    for joint in supplied:
        original = current.get(joint.get('name'))
        if (original is None or joint.get('type') != original.get('type') or
                any(joint.find(tag).attrib != original.find(tag).attrib for tag in ('parent', 'child'))):
            raise ValueError('SNOWBOT_JOINT_SOURCE_TOPOLOGY:'+joint.get('name'))
    # Update shared movable joints only. Keep the existing base, TCP/F/T,
    # camera and lidar frames with their matching original mesh assets.
    for joint in supplied:
        original = current[joint.get('name')]
        index = list(root).index(original)
        root.remove(original)
        root.insert(index, copy.deepcopy(joint))
    return root


def import_archive(archive_path, output):
    if hashlib.sha256(archive_path.read_bytes()).hexdigest() != SOURCE_SHA256:
        raise ValueError('SNOWBOT_SOURCE_HASH_MISMATCH')
    with ZipFile(archive_path) as archive:
        members = {info.filename: info for info in archive.infolist()}
        if any((not name.startswith(SOURCE_PREFIX) and
                name not in (SOURCE_PREFIX.rstrip('/') + '/', SOURCE_PREFIX.split('/')[0] + '/')) or
               '..' in Path(name).parts
               for name in members):
            raise ValueError('SNOWBOT_ARCHIVE_PATH')
        source = archive.read(SOURCE_PREFIX + 'urdf/snowbot.urdf')
        root = ET.fromstring(source)
        joints = root.findall('joint')
        if (root.get('name') != 'snowbot' or len(root.findall('link')) != 33 or len(joints) != 32 or
                {j.get('name') for j in joints if j.get('type') != 'fixed'} !=
                ACTIVE | {'head_joint_1', 'head_joint_2',
                          'arm_l_joint_8', 'arm_r_joint_8'} |
                {f'car_wheel_{wheel}_joint' for wheel in ('fl', 'fr', 'bl', 'br')}):
            raise ValueError('SNOWBOT_UNEXPECTED_MODEL_LAYOUT')
        for side in ('l', 'r'):
            sensor = [j for j in joints if j.find('child').get('link') == f'arm_{side}_ft_sensor']
            if len(sensor) != 1 or sensor[0].get('name') != 'arm_r_joint_8':
                raise ValueError('SNOWBOT_FT_JOINT_LAYOUT')
            sensor[0].set('name', f'arm_{side}_ft_sensor_joint')
        names = [j.get('name') for j in joints]
        if len(names) != len(set(names)):
            raise ValueError('SNOWBOT_DUPLICATE_JOINT')
        meshes = set()
        for mesh in root.findall('.//mesh'):
            uri = mesh.get('filename')
            prefix = 'package://snowbot/meshes/'
            if not uri.startswith(prefix) or Path(uri[len(prefix):]).name != uri[len(prefix):]:
                raise ValueError('SNOWBOT_MESH_URI')
            meshes.add(uri[len(prefix):])
            mesh.set('filename', 'package://snowbot_description/meshes/snowbot/' + uri[len(prefix):])
        (output / 'urdf').mkdir(parents=True, exist_ok=True)
        mesh_dir = output / 'meshes/snowbot'
        mesh_dir.mkdir(parents=True, exist_ok=True)
        for name in sorted(meshes):
            (mesh_dir / name).write_bytes(archive.read(SOURCE_PREFIX + 'meshes/' + name))
    return root


def write_variants(root, output):
    (output / 'urdf').mkdir(parents=True, exist_ok=True)
    joints = root.findall('joint')
    write_model(root, output / 'urdf/snowbot.urdf',
                'Full import; four movable wheels and visual/collision meshes retained.')
    for joint in joints:
        if joint.get('name', '').startswith('car_wheel_'):
            joint.set('type', 'fixed')
            for tag in ('axis', 'limit', 'dynamics', 'safety_controller', 'mimic'):
                element = joint.find(tag)
                if element is not None:
                    joint.remove(element)
    write_model(root, output / 'urdf/snowbot_display.urdf',
                'Stationary-base display; four wheels fixed, visual/collision meshes retained.')
    for link in root.findall('link'):
        for tag in ('visual', 'collision'):
            for element in link.findall(tag):
                link.remove(element)
    write_model(root, output / 'urdf/snowbot_control.urdf',
                'IK/QP kinematics; 20 movable axes, four wheels fixed, no visual/collision geometry.')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('archive', nargs='?', type=Path,
                        help='Optional original CAD ZIP; omit to reuse checked-in geometry/meshes')
    parser.add_argument('--output', type=Path, default=package_share("snowbot_description"),
                        help='Output description directory; without archive, only the three URDFs are regenerated')
    args = parser.parse_args()
    if args.archive is not None:
        root = import_archive(args.archive, args.output)
    else:
        # Reuse the maintained geometry base, not a second copy of its meshes.
        root = ET.parse(package_share("snowbot_description")/'urdf/snowbot.urdf').getroot()
    apply_joint_source(root)
    write_variants(root, args.output)
    print(f'Regenerated three URDF variants with joint source {JOINT_SOURCE_SHA256}')


if __name__ == '__main__':
    main()
